function interpolate(message, values) {
  return Object.entries(values ?? {}).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    message,
  );
}

export function siteText(locale, key, values) {
  const catalog = messages[locale] ?? messages.en;
  return interpolate(catalog[key] ?? messages.en[key] ?? key, values);
}

export function useSiteI18n() {
  const {i18n: {currentLocale}} = useDocusaurusContext();
  const locale = SITE_LOCALES.includes(currentLocale) ? currentLocale : 'en';
  const t = useCallback((key, values) => siteText(locale, key, values), [locale]);
  return useMemo(() => ({
    locale,
    t,
    formatNumber: (value) => Number(value).toLocaleString(locale),
  }), [locale, t]);
}
