// Only presentation fields are translated: IDs, recipe types, categories and
// routing keys remain stable so filtering and links keep the same behavior.
function translatePresentation(value, locale) {
  if (typeof value === 'string') return wikiText(locale, value);
  if (Array.isArray(value)) return value.map((item) => translatePresentation(item, locale));
  if (!value || typeof value !== 'object') return value;
  const protectedKeys = new Set(['id', 'identifier', 'slug', 'type', 'category', 'station', 'item', 'items', 'output', 'outputs', 'recipe', 'relatedItems', 'icon', 'image', 'source', 'href']);
  return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, protectedKeys.has(key) ? item : translatePresentation(item, locale)]));
}

